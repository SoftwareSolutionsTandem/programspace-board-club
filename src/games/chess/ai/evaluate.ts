/** Индекс таблицы для поля s со стороны цвета (белые смотрят снизу, чёрные — зеркально). */
const idx = (s: number, white: boolean) => (white ? (7 - (s >> 3)) * 8 + (s & 7) : (s >> 3) * 8 + (s & 7));

const ORDER: readonly Kind[] = ['p', 'n', 'b', 'r', 'q', 'k'];
// Готовые таблицы «цена + поле» по коду быстрой доски (1…6 белые, 9…14 чёрные) — со знаком для белых.
const build = (king: readonly number[]) => {
  const out: number[][] = [];
  for (let code = 0; code < 16; code++) {
    const k = ORDER[(code & 7) - 1];
    if (!k || (code & 7) > 6) {
      out.push(new Array(64).fill(0));
      continue;
    }
    const white = (code & 8) === 0;
    const table = k === 'k' ? king : T[k];
    out.push(Array.from({ length: 64 }, (_, s) => (white ? 1 : -1) * (VALUE[k] + table[idx(s, white)]!)));
  }
  return out;
};
const MID = build(T.k);
const END = build(KING_END);

export interface EvalWeights {
  /** Бонус за пару слонов. */
  readonly bishopPair: number;
}

/** Оценка доски в кодах быстрой доски (fastboard.ts), с точки зрения белых. */
export function evaluate(sq: Int8Array, w: EvalWeights): number {
  let heavy = 0;
  for (let s = 0; s < 64; s++) {
    const k = sq[s]! & 7;
    if (k >= 2 && k <= 5) heavy += VALUE[ORDER[k - 1]!];
  }
  const t = heavy <= 1600 ? END : MID;
  let score = 0, wb = 0, bb = 0;
  for (let s = 0; s < 64; s++) {
    const c = sq[s]!;
    if (!c) continue;
    score += t[c]![s]!;
    if (c === 3) wb++;
    else if (c === 11) bb++;
  }
  if (wb >= 2) score += w.bishopPair;
  if (bb >= 2) score -= w.bishopPair;
  return score;
}
